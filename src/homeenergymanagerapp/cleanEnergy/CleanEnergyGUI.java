    // Validates input, calculates through Calculable, shows and saves the result
    private void Calculate_ButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Calculate_ButtonActionPerformed
        // TODO add your handling code here:
        int panelCount;
        double electricityConsumption;
        
        if (Solar_Brand_Selector.getSelectedIndex() <= 0) {
            JOptionPane.showMessageDialog(null, "Select a brand first");
            return;
        }
        
        try {   
            
            SolarPanel solar = OptionManager.solar.get(Solar_Brand_Selector.getSelectedIndex());
            Calculable c = solar;
            
            panelCount = Integer.parseInt(PanelCount_Field.getText().trim());
            solar.setPanelCount(panelCount);
            electricityConsumption = Double.parseDouble(Electricity_Consumption_Field.getText().trim());

            if (panelCount <= 0 && electricityConsumption <= 0) {
                JOptionPane.showMessageDialog(null, "Values must be greater than 0");   
                return;
            }else if (panelCount <= 0) {
                JOptionPane.showMessageDialog(null, "Panel count must be greater than 0");   
                return;
            }else if (electricityConsumption <= 0) {
                JOptionPane.showMessageDialog(null, "Electricity consumption must be greater than 0");   
                return;
            }
            
            c.calculateAnnualSavings(panelCount,electricityConsumption);
            Saving_Text.setText(c.printSavings());

            solar.saveTXT(c.printSavings());
            solar.saveTXT("");
        
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Fill all the empty spaces");
        }
    }//GEN-LAST:event_Calculate_ButtonActionPerformed

    // Fills the text fields with the selected brand, or clears them
